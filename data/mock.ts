const generateProgress = (completedSteps: number, hasAbnormal: boolean = false, abnormalStep: number = -1) => {
  const steps = [
    { id: '1', step: '订单确认', status: 'completed' as const },
    { id: '2', step: '镶嵌准备', status: 'pending' as const },
    { id: '3', step: '执模工序', status: 'pending' as const },
    { id: '4', step: '镶嵌工序', status: 'pending' as const },
    { id: '5', step: '抛光工序', status: 'pending' as const },
    { id: '6', step: '质检', status: 'pending' as const },
    { id: '7', step: '交付客户', status: 'pending' as const },
  ]

  return steps.map((s, idx) => {
    let status = s.status
    if (idx < completedSteps) {
      status = 'completed'
    } else if (idx === completedSteps) {
      status = 'in_progress'
    }
    if (hasAbnormal && idx === abnormalStep) {
      status = 'abnormal'
    }
    return {
      ...s,
      status,
      startTime: idx <= completedSteps ? new Date(Date.now() - (completedSteps - idx) * 86400000) : undefined,
      endTime: idx < completedSteps ? new Date(Date.now() - (completedSteps - idx - 1) * 86400000) : undefined,
      operator: idx < completedSteps ? '李导购' : undefined,
    }
  })
}

