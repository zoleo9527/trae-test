export function getAssessmentById(id: string): Assessment | undefined {
  return mockAssessments.find(a => a.id === id);
}

export function getAssessmentsByOrder(orderId: string): Assessment[] {
  return mockAssessments.filter(a => a.orderId === orderId);
}

export function getAssessmentsByRider(riderId: string): Assessment[] {
  return mockAssessments.filter(a => a.riderId === riderId);
}

export function getAssessmentsByStatus(status: Assessment['status']): Assessment[] {
  return mockAssessments.filter(a => a.status === status);
}

export function getPendingAssessments(): Assessment[] {
  return mockAssessments.filter(a => a.status === 'pending_approval' || a.status === 'draft');
}
